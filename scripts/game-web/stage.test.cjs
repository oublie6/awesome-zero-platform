'use strict'
const {test}=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const os=require('node:os')
const path=require('node:path')
const {stage}=require('./stage.cjs')

test('Cocos+Vue staging is same-origin and public config is identical',t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'azp-web-stage-'))
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}))
 const web=path.join(root,'vue'),cocos=path.join(root,'cocos')
 fs.mkdirSync(web);fs.mkdirSync(cocos)
 fs.writeFileSync(path.join(web,'index.html'),'<html>Vue website</html>')
 fs.writeFileSync(path.join(cocos,'index.html'),'<html><canvas id="GameCanvas"></canvas></html>')
 fs.writeFileSync(path.join(cocos,'game.js'),'System.import("cc")')
 const manifest=stage(cocos,web,{apiBase:'https://play.example.org',
   socketEndpoint:'wss://play.example.org/ws'})
 assert.ok(manifest.configured)
 assert.ok(manifest.files.some(f=>f.path==='game/index.html'))
 assert.ok(manifest.files.some(f=>f.path==='game/game-config.js'))
 assert.deepEqual(fs.readFileSync(path.join(web,'game-config.js'),'utf8'),
   fs.readFileSync(path.join(web,'game/game-config.js'),'utf8'))
 assert.match(fs.readFileSync(path.join(web,'game/index.html'),'utf8'),/game-config.js/)
 assert.throws(()=>stage(cocos,web,{}),/Refusing to overwrite/)
})
test('staging rejects missing game exporter, symlinks and fake HTML',t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'azp-web-invalid-'))
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}))
 const web=path.join(root,'vue'),cocos=path.join(root,'cocos')
 fs.mkdirSync(web);fs.mkdirSync(cocos)
 fs.writeFileSync(path.join(web,'index.html'),'<html>vue</html>')
 fs.writeFileSync(path.join(cocos,'index.html'),'<html>not a Cocos build</html>')
 assert.throws(()=>stage(cocos,web,{}),/missing engine entrypoint/)
 fs.writeFileSync(path.join(cocos,'index.html'),'<html>GameCanvas</html>')
 fs.writeFileSync(path.join(cocos,'run.js'),'System.import("cc")')
 fs.symlinkSync(path.join(web,'index.html'),path.join(cocos,'escape.html'))
 assert.throws(()=>stage(cocos,web,{}),/Symlink forbidden/)
})
